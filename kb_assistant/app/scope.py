"""
领域边界守卫 —— 小助手【只聊本系统】。

【为什么要单独一层】
    「不能回答和项目无关的内容」这条要求，单靠系统提示词是不够的：
    提示词是「建议」，模型偶尔会越界。这一层做成【确定性规则】，
    在调用模型之前先把明显跑题的问题挡掉 —— 省一次 token，也更稳。

【三层防线】
    第 1 层（本文件，调用前）：确定性关键词判定，明显跑题直接拒答；
    第 2 层（提示词）：系统提示词写死领域边界，要求越界时输出固定标记；
    第 3 层（调用后）：检查回答里有没有越界标记，有就换成友好话术。

【设计取舍：宁可漏判，不可误杀】
    黑名单只收「几乎不可能出现在本系统问题里」的词。
    比如「写代码」不拦 —— 因为「怎么给这个系统加个接口」是合理问题；
    但「帮我写个爬虫」「写首唐诗」这种组合词会命中更具体的模式。
"""

from __future__ import annotations

import re

# 越界时模型必须输出的固定标记（前后端都用它对齐口径）
OUT_OF_SCOPE_MARKER = '[超出范围]'

# 统一的拒答话术
REFUSAL_TEXT = (
    '我只负责「学生管理系统」这块的事哦～'
    '学员档案、班级、老师和顾问、成绩、就业去向，'
    '或者这个系统本身的用法和数据库结构，都可以问我。'
)


# ---------------------------------------------------------------------------
# 确定性跑题模式
# ---------------------------------------------------------------------------
# 每条规则是 (正则, 命中原因)。正则必须足够具体，避免误杀。
_OUT_OF_SCOPE_PATTERNS: tuple[tuple[str, str], ...] = (
    # 天气
    (r'天气|气温|下雨|台风|降水量|天气预报', '天气'),
    # 行情 / 投资
    (r'股票|股价|大盘|涨停|跌停|基金.*净值|市盈率|加密货币|比特币|虚拟币|彩票|双色球', '投资理财'),
    # 时事 / 娱乐
    (r'新闻|头条|热搜|明星|八卦|娱乐圈|追剧|电影推荐|电视剧推荐', '时事娱乐'),
    # 生活闲聊
    (r'菜谱|食谱|减肥餐|健身计划|婆媳|相亲|恋爱|算命|占卜|星座运势|餐厅|饭店|美食推荐', '生活闲聊'),
    # 写作 / 创作
    (r'写[^，。？\n]{0,8}(?:诗|词|童谣|顺口溜)|情诗|藏头诗|写个笑话|讲个笑话|段子|小说大纲|起个网名', '文学创作'),
    # 通用编程（与本项目技术栈无关的独立题目）
    (r'爬虫|爬取.*(?:网站|网页)|写个游戏|算法题|数据结构|八股|leetcode|前端框架对比', '通用编程'),
    # 语言学习 / 通用生活知识
    (r'背单词|语法填空|雅思|托福|四六级|驾照|菜价|球赛比分|比分预测', '通用知识'),
    # 医疗 / 法律咨询
    (r'什么药|吃什么药|确诊|得了.*病|法律责任|赔偿标准|起诉.*怎么', '医疗法律咨询'),
)


def precheck(question: str) -> str | None:
    """
    调用模型【之前】的确定性检查。

    返回 None 表示「不拦，继续走模型」；
    返回字符串表示命中了哪一类跑题内容。
    """
    if not question or not question.strip():
        return None

    text = question.strip().lower()

    for pattern, reason in _OUT_OF_SCOPE_PATTERNS:
        if re.search(pattern, text):
            return reason

    return None


def is_out_of_scope_answer(answer: str) -> bool:
    """
    调用模型【之后】的检查：回答里是否带了越界标记。

    命中就把整条回答替换成统一话术，避免「半句在答、半句跑题」。
    """
    if not answer:
        return False
    return OUT_OF_SCOPE_MARKER in answer


def strip_marker(answer: str) -> str:
    """把回答里的越界标记去掉（模型有时会连着标记一起输出正文）。"""
    if not answer:
        return ''
    return answer.replace(OUT_OF_SCOPE_MARKER, '').strip()


def refusal(reason: str | None = None) -> str:
    """构造拒答文案。reason 只用于服务端日志，不展示给用户。"""
    return REFUSAL_TEXT
