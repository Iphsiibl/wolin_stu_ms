def locate_company(company: str | None) -> tuple[str, str]:
    """查一家公司的城市 / 省份。

    查不到就返回 ('其他', '其他') —— 宁可标成「其他」，
    也不要编一个城市上去，地图上的热力点必须是真去向。
    """
    if not company:
        return (OTHER_CITY, OTHER_PROVINCE)

    # 表里是精确匹配；顺手去一下首尾空格，
    # 免得库里存了 ' 百度 ' 这种带空格的写法就查不到。
    hit = COMPANY_CITIES.get(company.strip())
    if hit:
        return hit

    return (OTHER_CITY, OTHER_PROVINCE)


def company_cities_snapshot() -> dict[str, tuple[str, str]]:
    """返回一份映射表副本。

    给调用方（比如测试）用，避免外部直接改坏这张表。
    """
    return dict(COMPANY_CITIES)
